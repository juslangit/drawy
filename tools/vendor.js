// Copy the game icons Drawy uses out of lucide-static (ISC) into the app:
// renderer/icons.js for drawing them, src/icon-names.json for checking Claude's answers.
const fs = require('fs');
const path = require('path');

const ICONS = [
  'play', 'pause', 'settings', 'house', 'arrow-left', 'arrow-right', 'chevron-left', 'chevron-right',
  'x', 'check', 'plus', 'minus', 'heart', 'star', 'coins', 'gem', 'lock', 'lock-open', 'key',
  'volume-2', 'volume-x', 'music', 'trophy', 'medal', 'award', 'crown', 'shopping-cart', 'store',
  'user', 'users', 'menu', 'info', 'circle-help', 'refresh-cw', 'rotate-ccw', 'map', 'sword', 'swords',
  'shield', 'axe', 'bow-arrow', 'wand-sparkles', 'hammer', 'flask-conical', 'zap', 'flame', 'droplet',
  'leaf', 'apple', 'clock', 'timer', 'hourglass', 'share-2', 'mail', 'bell', 'message-circle', 'gift',
  'package', 'backpack', 'scroll', 'book-open', 'flag', 'skull', 'ghost', 'bomb', 'rocket', 'target',
  'crosshair', 'search', 'eye', 'log-out', 'power', 'battery-full', 'sparkles', 'moon', 'sun', 'image',
  'camera', 'list', 'layout-grid', 'maximize', 'gamepad-2', 'joystick', 'footprints', 'castle', 'tent',
  'anchor', 'fish',
];

const root = path.join(__dirname, '..');
const src = path.join(root, 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(src, name + '.svg'), 'utf8');
  out[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(root, 'renderer', 'icons.js'),
  '// Generated by tools/vendor.js from lucide-static (ISC licence). Do not edit.\nwindow.DRAWY_ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'src', 'icon-names.json'), JSON.stringify(ICONS) + '\n');
console.log(`Drawy: ${ICONS.length} icons copied.`);
